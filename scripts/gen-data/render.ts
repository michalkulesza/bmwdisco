const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

export const GENERATED_HEADER = '// generated by scripts/gen-data.ts — do not edit';

const isByteArray = (value: unknown): value is number[] =>
  Array.isArray(value) &&
  value.length > 0 &&
  value.every((item) => Number.isInteger(item) && item >= 0 && item <= 0xff);

const hexByte = (byte: number) => `0x${byte.toString(16).padStart(2, '0')}`;

export const literal = (value: unknown): string => {
  if (isByteArray(value)) return `[${value.map(hexByte).join(', ')}]`;
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;

  if (value && typeof value === 'object') {
    const body = Object.entries(value)
      .filter(([, item]) => item !== undefined)
      .map(
        ([key, item]) => `${IDENTIFIER.test(key) ? key : JSON.stringify(key)}: ${literal(item)}`,
      );
    return `{${body.join(', ')}}`;
  }

  return JSON.stringify(value);
};

export const fileWith = (...lines: string[]) => `${GENERATED_HEADER}\n${lines.join('\n')}\n`;
